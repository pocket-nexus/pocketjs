//! pocketjs-keyos — one PocketJS app as a KeyOS app on Passport Prime.
//!
//! The app registers a full-screen window with gui-server and asks for one
//! frame at a time with `request_redraw`. gui-server answers with a lent
//! 480x800 framebuffer (at most 40 per second, the panel's rate). Each lent
//! buffer gets one runtime step (guest turn, core tick, DrawList and its
//! damage). The Presenter names the regions that buffer needs, and the app
//! paints them in 32-row bands straight into it below the Control Center
//! rows, cleans the rows written from the data cache and returns the buffer
//! with `submit_frame`. Touches arrive as Press/Drag/Release messages in panel
//! coordinates and reach the guest through the runtime's contact latch. Every
//! 5 s the app logs its frame rate, the time of each phase per frame, and the
//! last burst of animation.

use std::time::{Duration, Instant};

use gui_server_api::consts::{SCREEN_HEIGHT, SCREEN_WIDTH};
use gui_server_api::touch::{Touch, TouchKind};
use gui_server_api::InputMessage;
use pocketjs_keyos_runtime::{Config, DamageRect, Phase, PixelOrder, Presenter, Runtime, Step};
use xous::{DropDeallocate, MemoryRange};

gui_server_api::use_api!();

/// Generated by tools/keyos.ts from the app's resolved build plan.
mod surface {
    include!(concat!(env!("POCKET_KEYOS_GEN"), "/surface.rs"));
}

static BUNDLE: &str = include_str!(concat!(env!("POCKET_KEYOS_GEN"), "/app.js"));
static PAK: &[u8] = include_bytes!(concat!(env!("POCKET_KEYOS_GEN"), "/app.pak"));

/// Passport Prime's framebuffer holds B,G,R,A; the hosted simulator's R,G,B,A.
#[cfg(keyos)]
const ORDER: PixelOrder = PixelOrder::Bgra;
#[cfg(not(keyos))]
const ORDER: PixelOrder = PixelOrder::Rgba;

/// Frames a lent buffer may lag behind the current frame.
const BUFFER_HISTORY: usize = 8;
/// Physical rows painted at a time. Each band starts at the last opaque op
/// that covers it, so short bands skip most layers beneath full-width rows.
const BAND_ROWS: usize = 32;

const STATS_EVERY: Duration = Duration::from_secs(5);
/// Frames without damage that end a burst of animation.
const BURST_IDLE_FRAMES: u32 = 8;

struct Lent {
    buffer: DropDeallocate,
    fresh: bool,
    arrived: Instant,
}

/// Rows of the lent buffer one presentation wrote, half-open, and the bytes.
#[derive(Clone, Copy, Default)]
struct Written {
    rows: (usize, usize),
    bytes: usize,
}

/// Wall time of each phase of one frame.
#[derive(Clone, Copy, Default)]
struct Phases {
    /// From `request_redraw` to the lent buffer's arrival.
    wait: Duration,
    guest: Duration,
    draw: Duration,
    paint: Duration,
    clean: Duration,
    submit: Duration,
}

impl Phases {
    fn total(&self) -> Duration {
        self.guest + self.draw + self.paint + self.clean + self.submit
    }

    fn add(&mut self, other: Phases) {
        self.wait += other.wait;
        self.guest += other.guest;
        self.draw += other.draw;
        self.paint += other.paint;
        self.clean += other.clean;
        self.submit += other.submit;
    }

    fn describe(&self, frames: u32) -> String {
        let ms = |d: Duration| d.as_secs_f64() * 1e3 / f64::from(frames.max(1));
        format!(
            "wait {:.1}, guest {:.1}, draw {:.1}, paint {:.1}, clean {:.1}, submit {:.1}",
            ms(self.wait),
            ms(self.guest),
            ms(self.draw),
            ms(self.paint),
            ms(self.clean),
            ms(self.submit)
        )
    }
}

#[derive(Default)]
struct Stats {
    frames: u32,
    phases: Phases,
    worst: Duration,
    repainted: u64,
    bytes: usize,
}

impl Stats {
    fn add(&mut self, phases: Phases, repainted: u64, written: Written) {
        self.frames += 1;
        self.phases.add(phases);
        self.worst = self.worst.max(phases.total());
        self.repainted += repainted;
        self.bytes += written.bytes;
    }

    fn report(&self, elapsed: Duration, area: u64, bursts: &Bursts) {
        let n = self.frames.max(1);
        log::info!(
            "{:.1} fps; ms per frame {}; worst {:.1} ms; changed {:.1}%, wrote {} KiB; {}",
            f64::from(self.frames) / elapsed.as_secs_f64(),
            self.phases.describe(n),
            self.worst.as_secs_f64() * 1e3,
            self.repainted as f64 * 100.0 / (f64::from(n) * area as f64),
            self.bytes / n as usize / 1024,
            bursts.describe(area),
        );
    }
}

/// One run of frames that changed something. `foundation logs` streams only
/// new lines, so every periodic report repeats the last closed burst: drive a
/// gesture, then attach the log stream.
#[derive(Clone, Copy)]
struct Burst {
    frames: u32,
    first: Instant,
    last: Instant,
    worst: Duration,
    longest_gap: Duration,
    changed: u64,
    phases: Phases,
    /// The slowest frame: its index in the burst and its phases.
    slowest: (u32, Phases),
}

#[derive(Default)]
struct Bursts {
    open: Option<Burst>,
    idle: u32,
    closed: Option<Burst>,
    previous: Option<Instant>,
}

impl Bursts {
    fn add(&mut self, changed: u64, phases: Phases) {
        let now = Instant::now();
        let gap = self.previous.map_or(Duration::ZERO, |p| now - p);
        self.previous = Some(now);
        if changed == 0 {
            if self.open.is_some() {
                self.idle += 1;
                if self.idle >= BURST_IDLE_FRAMES {
                    self.closed = self.open.take();
                }
            }
            return;
        }
        self.idle = 0;
        let burst = self.open.get_or_insert(Burst {
            frames: 0,
            first: now,
            last: now,
            worst: Duration::ZERO,
            longest_gap: Duration::ZERO,
            changed: 0,
            phases: Phases::default(),
            slowest: (0, Phases::default()),
        });
        if burst.frames > 0 {
            burst.longest_gap = burst.longest_gap.max(gap);
        }
        if phases.total() > burst.worst {
            burst.slowest = (burst.frames, phases);
        }
        burst.frames += 1;
        burst.last = now;
        burst.worst = burst.worst.max(phases.total());
        burst.changed += changed;
        burst.phases.add(phases);
    }

    fn describe(&self, area: u64) -> String {
        let Some(b) = self.closed else { return String::from("no burst yet") };
        let span = (b.last - b.first).as_secs_f64();
        format!(
            "last burst {} frames at {:.1} fps, ms per frame {}, worst {:.1} ms (frame {}: {}), longest gap {:.1} ms, changed {:.0}%",
            b.frames,
            if span > 0.0 { f64::from(b.frames - 1) / span } else { 0.0 },
            b.phases.describe(b.frames),
            b.worst.as_secs_f64() * 1e3,
            b.slowest.0,
            b.slowest.1.describe(1),
            b.longest_gap.as_secs_f64() * 1e3,
            b.changed as f64 * 100.0 / (f64::from(b.frames) * area as f64),
        )
    }
}

/// Repaint `regions` (logical) into `dst`, a lent framebuffer, band by band.
/// The bands go straight into the lent buffer: on Passport Prime it streams
/// writes about twice as fast as the app's heap, and a band painted several
/// times gains nothing from the cache, so a staging buffer only adds a copy.
fn paint(runtime: &Runtime, regions: &[DamageRect], dst: &mut [u8]) -> Written {
    let d = runtime.density() as usize;
    let stride = SCREEN_WIDTH * 4;
    let band = (BAND_ROWS / d).max(1) as i32;
    let mut written = Written { rows: (usize::MAX, 0), bytes: 0 };
    for r in regions {
        let mut y = r.y0;
        while y < r.y1 {
            let y1 = (y + band).min(r.y1);
            let window = DamageRect::new(r.x0, y, r.x1, y1);
            let (top, bottom) = (surface::TOP + y as usize * d, surface::TOP + y1 as usize * d);
            let (c0, c1) = (r.x0 as usize * d * 4, r.x1 as usize * d * 4);
            runtime.paint_rows(window, &mut dst[top * stride..bottom * stride]);
            written.rows = (written.rows.0.min(top), written.rows.1.max(bottom));
            written.bytes += (bottom - top) * (c1 - c0);
            y = y1;
        }
    }
    if written.bytes == 0 {
        written.rows = (0, 0);
    }
    written
}

fn main() {
    log_server::init_wait(env!("CARGO_CRATE_NAME")).unwrap();
    log::set_max_level(log::LevelFilter::Info);

    let gui = GuiApi::register(surface::TITLE, SCREEN_HEIGHT).expect("register with gui-server");
    let config = Config {
        host_id: surface::HOST_ID,
        host_abi: surface::HOST_ABI,
        width: surface::WIDTH,
        height: surface::HEIGHT,
        density: surface::DENSITY,
        tick_hz: surface::TICK_HZ,
        order: ORDER,
    };
    let booted = Instant::now();
    let mut runtime = match Runtime::boot(&config, BUNDLE, PAK) {
        Ok(runtime) => runtime,
        Err(error) => {
            log::error!("{}: boot failed: {error:?}", surface::TITLE);
            return;
        }
    };
    let (width, _) = runtime.size();
    assert_eq!(width as usize, SCREEN_WIDTH, "the surface spans the panel's width");
    log::info!(
        "{}: {}x{} logical at {}x, {} Hz, booted in {} ms",
        surface::TITLE,
        surface::WIDTH,
        surface::HEIGHT,
        surface::DENSITY,
        surface::TICK_HZ,
        booted.elapsed().as_millis()
    );

    let mut presenter = Presenter::new(BUFFER_HISTORY);
    let area = u64::from(surface::WIDTH) * u64::from(surface::HEIGHT);
    let mut lent: Option<Lent> = None;
    let mut visible = true;
    let mut stats = Stats::default();
    let mut bursts = Bursts::default();
    let mut window = Instant::now();
    gui.request_redraw().ok();
    let mut requested = Instant::now();

    'events: loop {
        if !visible || lent.is_none() {
            match gui.receive_input() {
                Ok((event, envelope)) => {
                    if !handle(event, envelope, &mut runtime, &mut presenter, &mut lent, &mut visible, &gui) {
                        break 'events;
                    }
                }
                Err(error) => {
                    log::error!("receiving input failed: {error:?}");
                    break 'events;
                }
            }
        }
        while let Some((event, envelope)) = gui.try_receive_input() {
            if !handle(event, envelope, &mut runtime, &mut presenter, &mut lent, &mut visible, &gui) {
                break 'events;
            }
        }
        if !visible {
            continue;
        }
        let Some(Lent { buffer, fresh, arrived }) = lent.take() else { continue };
        let wait = arrived.saturating_duration_since(requested);

        let step = match runtime.step() {
            Ok(step) => step,
            Err(error) => {
                log::error!("{error:?}");
                Step::default()
            }
        };
        presenter.record(&step.regions);
        let regions = presenter.regions(runtime.bounds(), fresh);
        let painted = Instant::now();
        let mut range = buffer.leak();
        let written = paint(&runtime, &regions, range.as_slice_mut::<u8>());
        let cleaned = Instant::now();
        clean(range, written);
        let submitted = Instant::now();
        if let Err(error) = gui.submit_frame(range) {
            log::error!("submitting a frame failed: {error:?}");
        }
        let t = step.timing;
        let phases = Phases {
            wait,
            guest: t.guest + t.tick,
            draw: t.draw,
            paint: cleaned - painted,
            clean: submitted - cleaned,
            submit: submitted.elapsed(),
        };
        stats.add(phases, step.area(), written);
        bursts.add(step.area(), phases);
        gui.request_redraw().ok();
        requested = Instant::now();

        if window.elapsed() >= STATS_EVERY {
            stats.report(window.elapsed(), area, &bursts);
            stats = Stats::default();
            window = Instant::now();
        }
    }
    log::info!("{}: closing", surface::TITLE);
}

/// Apply one gui-server message. Returns false when the app must exit.
fn handle(
    event: InputMessage,
    envelope: xous::MessageEnvelope,
    runtime: &mut Runtime,
    presenter: &mut Presenter,
    lent: &mut Option<Lent>,
    visible: &mut bool,
    gui: &GuiApi,
) -> bool {
    match event {
        InputMessage::Touch => {
            if let Some(touch) = Touch::try_from_input_message(&envelope.body) {
                let phase = match touch.kind {
                    TouchKind::Press => Phase::Down,
                    TouchKind::Drag => Phase::Move,
                    TouchKind::Release => Phase::Up,
                };
                runtime.touch(phase, touch.id, touch.x as i32, touch.y as i32 - surface::TOP as i32);
            }
        }
        InputMessage::FrameBuffer => {
            let message = envelope.take_message();
            if let Some(memory) = message.memory_message() {
                *lent = Some(Lent {
                    buffer: DropDeallocate::new(memory.buf),
                    fresh: memory.valid.is_some(),
                    arrived: Instant::now(),
                });
            }
        }
        InputMessage::Visible => {
            *visible = true;
            presenter.reset();
            gui.request_redraw().ok();
        }
        InputMessage::Hidden => {
            *visible = false;
            runtime.cancel_touches();
            runtime.collect_garbage();
        }
        InputMessage::CloseRequested => return false,
        _ => {}
    }
    true
}

/// Write the rows a presentation touched back to memory so the display
/// controller reads them.
#[cfg(keyos)]
fn clean(range: MemoryRange, written: Written) {
    const PAGE: usize = 4096;
    let (first, last) = written.rows;
    if first >= last {
        return;
    }
    let stride = SCREEN_WIDTH * 4;
    let start = first * stride / PAGE * PAGE;
    let end = (last * stride).div_ceil(PAGE).saturating_mul(PAGE).min(range.len());
    // SAFETY: the sub-range lies inside the lent buffer this process maps.
    let rows = unsafe { MemoryRange::new(range.as_ptr() as usize + start, end - start) };
    let rows = rows.unwrap_or(range);
    xous::syscall::flush_cache(rows, xous::CacheOperation::Clean).expect("clean cache");
}

#[cfg(not(keyos))]
fn clean(_range: MemoryRange, _written: Written) {}
