//! Build-script support for programs that embed their exported profile.
//!
//! `pocket build` exports the selected profile as `pocket_profile.rs` and
//! names it in `POCKETJS_PROFILE_RS`. A program's `build.rs` calls [`emit`],
//! then includes `OUT_DIR/pocket_profile.rs` as a module. The module always
//! defines `EXPORTED`, `ID`, `HOST_ABI`, `CADENCES`, `PROFILE_HASH` and
//! `profile() -> Option<pocket_runtime::Profile>`; `profile()` is `Some` when a
//! profile was exported for the build.
use std::{env, fs, path::PathBuf};

/// Whether a build without an exported profile is an error or a stub.
pub enum Export {
    /// Device programs: a missing export fails the build.
    Required,
    /// Programs that also build as plain workspace members: the stub leaves
    /// `profile()` returning `None`, and the program reports it at startup.
    Optional,
}

const BANNER: &str = "// Generated by pocket profile export; do not edit.";
const STUB: &str = "// No profile was exported for this build (POCKETJS_PROFILE_RS is unset).
pub const EXPORTED: bool = false;
pub const ID: &str = \"\";
pub const HOST_ABI: u32 = 0;
pub const CADENCES: &[u32] = &[];
pub const PROFILE_HASH: [u8; 32] = [0; 32];
pub fn profile() -> Option<::pocket_runtime::Profile> {
    None
}
";

/// Write `OUT_DIR/pocket_profile.rs` from `POCKETJS_PROFILE_RS`.
pub fn emit(export: Export) {
    println!("cargo:rerun-if-env-changed=POCKETJS_PROFILE_RS");
    let out = PathBuf::from(env::var_os("OUT_DIR").expect("OUT_DIR")).join("pocket_profile.rs");
    match env::var_os("POCKETJS_PROFILE_RS") {
        Some(path) => {
            let path = PathBuf::from(path);
            println!("cargo:rerun-if-changed={}", path.display());
            let text = fs::read_to_string(&path)
                .unwrap_or_else(|error| panic!("POCKETJS_PROFILE_RS={}: {error}", path.display()));
            assert!(
                text.starts_with(BANNER),
                "POCKETJS_PROFILE_RS does not name a pocket profile export: {}",
                path.display()
            );
            fs::write(&out, text).expect("write pocket_profile.rs");
        }
        None => match export {
            Export::Required => panic!(
                "POCKETJS_PROFILE_RS is unset: build this program through `pocket build`, which exports its profile"
            ),
            Export::Optional => fs::write(&out, STUB).expect("write pocket_profile.rs"),
        },
    }
}
