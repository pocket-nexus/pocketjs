// tools/keyos.ts — build a PocketJS app into the KeyOS app hosts/keyos/app and
// run it on Foundation's Passport Prime, in its simulator, or headless.
//
//   bun tools/keyos.ts preview  [--manifest=…] [preview actions…]
//   bun tools/keyos.ts sim      [--manifest=…]
//   bun tools/keyos.ts build    [--manifest=…] [--release]
//   bun tools/keyos.ts sideload [--manifest=…] [--release] [--no-run]
//   bun tools/keyos.ts pack     [--manifest=…] [--release]
//
// Every command resolves the manifest (default: Pocket Clear's) against the
// passport-prime-dev profile, compiles app.js + app.pak at the panel's 40 Hz,
// and writes hosts/keyos/app/gen/ and app-config.toml. `preview` runs the
// runtime crate's preview example on this machine. The other commands run the
// Foundation CLI in hosts/keyos/app: `sim` builds for the hosted simulator,
// `build`/`sideload`/`pack` cross-compile for armv7a-unknown-xous-elf, which
// needs the SDK's Nix shell (`foundation develop`) or, outside it, the
// target's sysroot installed into the SDK's Rust toolchain.

import { createHash } from "node:crypto";
import { copyFileSync, existsSync, lstatSync, mkdirSync, readFileSync, symlinkSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { buildGuestBundle, mustRunCommand } from "./native-host-build.ts";
import {
  PASSPORT_PRIME_STATUS_BAR_ROWS,
  PASSPORT_PRIME_TARGET,
  resolvePassportPrimeBuildPlan,
} from "./passport-prime-profile.ts";

const LABEL = "PocketJS KeyOS";
/** The panel refreshes at 40 Hz (gui-server `consts::FPS`). */
const TICK_HZ = 40;
const XOUS_TARGET = "armv7a-unknown-xous-elf";
const RUST_TOOLCHAIN = "nightly-2026-04-11";

const repository = fileURLToPath(new URL("..", import.meta.url));
const appDir = join(repository, "hosts/keyos/app");
const runtimeDir = join(repository, "hosts/keyos/runtime");
const sdk = process.env.FOUNDATION_SDK_ROOT ?? join(homedir(), ".foundation/sdk/current");

const argv = Bun.argv.slice(2);
const command = argv.find(arg => !arg.startsWith("--")) ?? "preview";
const option = (name: string) =>
  argv.find(arg => arg.startsWith(`--${name}=`))?.slice(name.length + 3);
const manifestPath = resolve(option("manifest") ?? join(repository, "apps/clear/pocket.passport-prime.json"));
const release = argv.includes("--release");

function run(program: string, args: readonly string[], cwd: string, env: NodeJS.ProcessEnv = process.env): void {
  const result = Bun.spawnSync({ cmd: [program, ...args], cwd, env, stdio: ["inherit", "inherit", "inherit"] });
  if (result.exitCode !== 0) {
    throw new Error(`${LABEL}: ${program} ${args.join(" ")} failed (${result.exitCode})`);
  }
}

/** A stable 16-byte KeyOS app id for a PocketJS app id. */
function keyosAppId(appId: string): string {
  return `0x${createHash("sha256").update(`pocketjs:${appId}`).digest("hex").slice(0, 32)}`;
}

function tomlString(value: string): string {
  return JSON.stringify(value);
}

function prepare(): void {
  const bundle = buildGuestBundle({
    label: LABEL,
    repository,
    target: PASSPORT_PRIME_TARGET,
    resolvePlan: resolvePassportPrimeBuildPlan,
    manifestPath,
    planPath: join(repository, ".pocket/passport-prime/app.plan.json"),
    outputDirectory: join(repository, "dist/passport-prime/guest"),
    tickHz: TICK_HZ,
  });
  const { inputs } = bundle;
  const gen = join(appDir, "gen");
  mkdirSync(gen, { recursive: true });
  copyFileSync(bundle.javaScript, join(gen, "app.js"));
  copyFileSync(bundle.pack, join(gen, "app.pak"));
  writeFileSync(
    join(gen, "surface.rs"),
    [
      `// Generated by tools/keyos.ts from ${inputs.app.id} ${inputs.app.version}.`,
      `pub const TITLE: &str = ${JSON.stringify(inputs.app.title)};`,
      `pub const HOST_ID: &str = ${JSON.stringify(inputs.target)};`,
      `pub const HOST_ABI: u32 = ${inputs.hostAbi};`,
      `pub const WIDTH: u32 = ${inputs.viewport.logical[0]};`,
      `pub const HEIGHT: u32 = ${inputs.viewport.logical[1]};`,
      `pub const DENSITY: u32 = ${inputs.viewport.rasterDensity};`,
      `pub const TICK_HZ: u32 = ${TICK_HZ};`,
      `/// Panel row the surface starts at, below the collapsed Control Center.`,
      `pub const TOP: usize = ${PASSPORT_PRIME_STATUS_BAR_ROWS};`,
      "",
    ].join("\n"),
  );
  writeFileSync(
    join(appDir, "app-config.toml"),
    [
      `# Generated by tools/keyos.ts from ${inputs.app.id}.`,
      `app-name = "pocketjs-keyos"`,
      `friendly-app-name = ${tomlString(inputs.app.title)}`,
      `launcher-app-name = ${tomlString(inputs.app.title)}`,
      `description = ${tomlString(`${inputs.app.title}, a PocketJS app`)}`,
      `icon = "resources/icon.svg"`,
      `app-id = "${keyosAppId(inputs.app.id)}"`,
      `min-keyos-version = "1.4.0"`,
      ...(process.env.FOUNDATION_SIGNING_IDENTITY
        ? [`signing-identity = ${tomlString(process.env.FOUNDATION_SIGNING_IDENTITY)}`]
        : []),
      "",
      "[publisher]",
      `name = "Pocket Nexus"`,
      `contact-email = "support@pocket.nexus"`,
      `support-url = "https://pocketjs.dev"`,
      "",
      "[permissions]",
      `template = ["gui-app"]`,
      "",
    ].join("\n"),
  );
  console.log(`${LABEL}: ${inputs.app.title} ${inputs.viewport.logical.join("x")} @${inputs.viewport.rasterDensity}x, ${TICK_HZ} Hz -> ${gen}`);
}

function linkSdk(): void {
  if (!existsSync(join(sdk, "lib/keyos"))) {
    throw new Error(`${LABEL}: no Foundation SDK at ${sdk}; install it from https://docs.foundation.xyz/developers/get-started/`);
  }
  const link = join(appDir, ".foundation-sdk/current");
  mkdirSync(dirname(link), { recursive: true });
  let present = false;
  try {
    present = lstatSync(link).isSymbolicLink();
  } catch {}
  if (!present) symlinkSync(sdk, link);
}

/** The bin directory of a rustup toolchain's host LLVM tools. */
function llvmTools(): string {
  const sysroot = mustRunCommand(LABEL, "rustc", [`+${RUST_TOOLCHAIN}`, "--print", "sysroot"], repository);
  const host = mustRunCommand(LABEL, "rustc", [`+${RUST_TOOLCHAIN}`, "-vV"], repository).match(/host: (\S+)/)?.[1];
  return join(sysroot, "lib/rustlib", host ?? "", "bin");
}

/** QuickJS's source directory in the rquickjs-sys package Cargo resolved for the app. */
function quickJsSources(): string {
  const metadata = JSON.parse(
    mustRunCommand(LABEL, "cargo", [`+${RUST_TOOLCHAIN}`, "metadata", "--format-version=1"], appDir),
  ) as { packages: { name: string; manifest_path: string }[] };
  const sys = metadata.packages.find(p => p.name === "rquickjs-sys");
  if (!sys) throw new Error(`${LABEL}: rquickjs-sys is not in the app's dependency graph`);
  return join(dirname(sys.manifest_path), "quickjs");
}

/**
 * Compiler settings for the C half of the device build: QuickJS (in
 * rquickjs-sys) and the libc shim (hosts/keyos/runtime/build.rs). Apple's
 * clang cross-compiles for the target's armv7a-none-eabihf triple against
 * hosts/keyos/libc/include; LLVM's archiver writes the ELF archives.
 */
function deviceEnv(): NodeJS.ProcessEnv {
  const clang = "/usr/bin/clang";
  const resources = mustRunCommand(LABEL, clang, ["-print-resource-dir"], repository);
  const include = join(repository, "hosts/keyos/libc/include");
  const flags = [
    "--target=armv7a-none-eabihf",
    "-mcpu=cortex-a5",
    "-mthumb",
    "-mfpu=neon-vfpv4",
    "-mfloat-abi=hard",
    "-fPIC",
    "-nostdinc",
    `-isystem${include}`,
    `-isystem${join(resources, "include")}`,
    "-D__STDC_NO_ATOMICS__=1",
  ];
  const key = XOUS_TARGET.replace(/-/g, "_");
  const tools = llvmTools();
  return {
    ...process.env,
    [`CC_${key}`]: clang,
    [`AR_${key}`]: join(tools, "llvm-ar"),
    [`CFLAGS_${key}`]: flags.join(" "),
    [`BINDGEN_EXTRA_CLANG_ARGS_${key}`]: flags.join(" "),
    LIBCLANG_PATH: process.env.LIBCLANG_PATH ?? dirname(dirname(resources)),
    POCKET_KEYOS_QUICKJS_INCLUDE: quickJsSources(),
    RUSTUP_TOOLCHAIN: process.env.RUSTUP_TOOLCHAIN ?? RUST_TOOLCHAIN,
  };
}

function preview(): void {
  const plan = JSON.parse(readFileSync(join(repository, ".pocket/passport-prime/app.plan.json"), "utf8"));
  const [width, height] = plan.viewport.logical as [number, number];
  const actions = argv.filter(arg => /^--(wait|tap|drag|down|move|up|shot)\b/.test(arg));
  run(
    "cargo",
    [
      "run", "--release", "--quiet", "--example", "preview", "--",
      join(appDir, "gen/app.js"),
      join(appDir, "gen/app.pak"),
      join(repository, "dist/passport-prime/preview"),
      `--size=${width}x${height}`,
      `--density=${plan.viewport.rasterDensity}`,
      `--hz=${TICK_HZ}`,
      `--host=${plan.target.id}`,
      `--abi=${plan.target.hostAbi}`,
      ...(actions.length ? actions : ["--wait=40", "--shot=idle"]),
    ],
    runtimeDir,
  );
}

function foundation(args: readonly string[], env: NodeJS.ProcessEnv): void {
  run(join(sdk, "bin/foundation"), args, appDir, { ...env, FOUNDATION_SDK_ROOT: sdk });
}

prepare();
switch (command) {
  case "preview":
    preview();
    break;
  case "sim":
    linkSdk();
    foundation(["sim"], { ...process.env, RUSTUP_TOOLCHAIN: process.env.RUSTUP_TOOLCHAIN ?? RUST_TOOLCHAIN });
    break;
  case "build":
  case "sideload":
  case "pack": {
    linkSdk();
    const passthrough = argv.filter(arg => arg === "--no-run");
    foundation([command, ...(release ? ["--release"] : []), ...passthrough], deviceEnv());
    break;
  }
  default:
    throw new Error(`${LABEL}: unknown command ${command}; use preview, sim, build, sideload or pack`);
}
