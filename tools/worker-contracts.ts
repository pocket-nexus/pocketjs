import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { FactKind, ResourceKind, ResourceStatus, WORKER_LIMITS, WORKER_PROTOCOL_VERSION } from "../contracts/spec/worker.ts";

export function workerProtocolHeader(): string {
  const enums = [ResourceKind, ResourceStatus, FactKind].map(values =>
    `enum {\n${Object.entries(values).map(([name, value]) => `  POCKET_WORKER_${name.toUpperCase()} = ${value}`).join(",\n")}\n};\n`).join("");
  const limits = { RESOURCES: WORKER_LIMITS.resources, REQUESTS: WORKER_LIMITS.requests,
    PAYLOAD: WORKER_LIMITS.payloadBytes, EVENTS: WORKER_LIMITS.events, TIMERS: WORKER_LIMITS.timers, CHANNELS: WORKER_LIMITS.channels };
  return "/* Generated by tools/worker-contracts.ts from contracts/spec/worker.ts. */\n" +
    "#ifndef POCKET_WORKER_PROTOCOL_H\n#define POCKET_WORKER_PROTOCOL_H\n" +
    `#define POCKET_WORKER_PROTOCOL_VERSION ${WORKER_PROTOCOL_VERSION}\n` + enums +
    Object.entries(limits).map(([name, value]) => `#define POCKET_WORKER_MAX_${name} ${value}\n`).join("") +
    "#endif\n";
}

if (import.meta.main) {
  const path = resolve(fileURLToPath(new URL("..", import.meta.url)), "engine/worker/include/pocket/worker_protocol.h");
  const generated = workerProtocolHeader();
  if (process.argv.includes("--check")) {
    if (readFileSync(path, "utf8") !== generated) throw new Error("stale worker protocol header; run bun tools/worker-contracts.ts");
  } else await Bun.write(path, generated);
}
