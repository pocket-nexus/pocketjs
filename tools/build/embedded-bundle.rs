//! Build-time embedding of the one compiled bundle a handheld program carries,
//! shared by programs/psp/build.rs and programs/vita/build.rs.
//!
//! `generate` copies the bundle verbatim to `$OUT_DIR/app.pkb` and writes
//! `$OUT_DIR/bundle.rs`, which defines `BUNDLE: &[u8]`: those bytes 16-byte
//! aligned, or empty when the program embeds no application (the generic
//! runtime).
use std::{
    fs,
    path::{Path, PathBuf},
};

/// The build identity a program reports as `POCKETJS_BUNDLE_HASH`.
#[derive(Clone, Copy)]
#[allow(dead_code)] // Each build script selects one.
pub enum Identity {
    /// FNV-1a64 of the embedded bundle bytes; `none` without one (PSP).
    Bundle,
    /// FNV-1a64 of the application's JS and pak in the output directory
    /// (Vita bench receipts).
    Sources,
}

pub struct Config<'a> {
    pub identity: Identity,
    /// The application's output name, which names its JS and pak.
    pub output: &'a str,
    /// Whether the program embeds an application.
    pub enabled: bool,
    /// The directory holding `<output>.js` and `<output>.pak`.
    pub dist: &'a Path,
    pub out: &'a Path,
    /// The compiled bundle, an absolute path: required when `enabled`.
    pub package: Option<&'a Path>,
}
#[derive(Debug)]
pub struct Generated {
    pub hash: String,
    /// The files the build script reruns on.
    pub inputs: Vec<PathBuf>,
}
fn read(path: &Path, inputs: &mut Vec<PathBuf>) -> Result<Vec<u8>, String> {
    inputs.push(path.to_owned());
    fs::read(path).map_err(|error| format!("{}: {error}", path.display()))
}
fn write(path: &Path, value: impl AsRef<[u8]>) -> Result<(), String> {
    fs::write(path, value).map_err(|error| format!("{}: {error}", path.display()))
}
fn fnv(chunks: &[&[u8]]) -> String {
    let mut hash = 0xcbf2_9ce4_8422_2325u64;
    for byte in chunks.iter().flat_map(|chunk| chunk.iter()) {
        hash = (hash ^ u64::from(*byte)).wrapping_mul(0x0000_0100_0000_01b3);
    }
    format!("{hash:016x}")
}
pub fn generate(config: Config<'_>) -> Result<Generated, String> {
    if !config.enabled && config.package.is_some() {
        return Err("the generic runtime cannot embed a bundle".into());
    }
    // The runtime admits compiled bundles only; a raw JS/pak pair has no
    // plan, identity or profile hash to admit.
    if config.enabled && config.package.is_none() {
        return Err(
            "POCKETJS_EMBED_APP=1 requires POCKETJS_EMBED_BUNDLE: embed a compiled .pkb bundle"
                .into(),
        );
    }
    if config.package.is_some_and(|path| !path.is_absolute()) {
        return Err("POCKETJS_EMBED_BUNDLE must be an absolute captured bundle path".into());
    }
    let mut inputs = Vec::new();
    let bundle = match config.package {
        Some(path) => read(path, &mut inputs)?,
        None => Vec::new(),
    };
    let hash = match config.identity {
        Identity::Bundle if config.enabled => fnv(&[&bundle]),
        Identity::Bundle => "none".into(),
        Identity::Sources if config.enabled => {
            let js = read(&config.dist.join(format!("{}.js", config.output)), &mut inputs)?;
            let pak_path = config.dist.join(format!("{}.pak", config.output));
            inputs.push(pak_path.clone());
            let pak = if pak_path.exists() {
                fs::read(&pak_path).map_err(|error| error.to_string())?
            } else {
                Vec::new()
            };
            fnv(&[&js, &pak])
        }
        Identity::Sources => fnv(&[]),
    };
    write(&config.out.join("app.pkb"), &bundle)?;
    let source = if bundle.is_empty() {
        "// GENERATED by tools/build/embedded-bundle.rs.\npub static BUNDLE: &[u8] = &[];\n".into()
    } else {
        format!(
            "// GENERATED by tools/build/embedded-bundle.rs.\n\
             pub static BUNDLE: &[u8] = {{\n\
             \x20   #[repr(align(16))]\n\
             \x20   struct Aligned<const N: usize>([u8; N]);\n\
             \x20   static BYTES: Aligned<{}> = Aligned(*include_bytes!(concat!(env!(\"OUT_DIR\"), \"/app.pkb\")));\n\
             \x20   &BYTES.0\n\
             }};\n",
            bundle.len()
        )
    };
    write(&config.out.join("bundle.rs"), source)?;
    Ok(Generated { hash, inputs })
}

#[cfg(test)]
mod tests {
    use super::*;
    fn directory(name: &str) -> PathBuf {
        let path = PathBuf::from(std::env::var_os("POCKET_EMBED_TEST_DIR").unwrap()).join(name);
        fs::create_dir_all(&path).unwrap();
        path
    }
    fn config<'a>(path: &'a Path, package: Option<&'a Path>) -> Config<'a> {
        Config {
            identity: Identity::Bundle,
            output: "hero-main",
            enabled: true,
            dist: path,
            out: path,
            package,
        }
    }
    #[test]
    fn captured_package_is_embedded_verbatim_and_aligned() {
        let path = directory("single");
        let package = path.join("captured.pkb");
        fs::write(&package, b"original package with private sections\0\xff").unwrap();
        let generated = generate(config(&path, Some(&package))).unwrap();
        assert_eq!(generated.inputs, vec![package.clone()]);
        assert_eq!(generated.hash, fnv(&[&fs::read(&package).unwrap()]));
        assert_eq!(
            fs::read(path.join("app.pkb")).unwrap(),
            fs::read(&package).unwrap()
        );
        // Compile the emitted source: its backing bytes and 16-byte alignment.
        let main = path.join("bundle-check.rs");
        fs::write(&main, format!("include!({:?});\nfn main() {{ assert_eq!(BUNDLE, include_bytes!({:?})); assert_eq!(BUNDLE.as_ptr() as usize % 16, 0); }}", path.join("bundle.rs"), package)).unwrap();
        let binary = path.join("bundle-check");
        assert!(
            std::process::Command::new(std::env::var_os("RUSTC").unwrap_or("rustc".into()))
                .arg(&main)
                .arg("-o")
                .arg(&binary)
                .env("OUT_DIR", &path)
                .status()
                .unwrap()
                .success()
        );
        assert!(std::process::Command::new(binary)
            .status()
            .unwrap()
            .success());
        fs::write(&package, b"changed original bytes").unwrap();
        let next = generate(config(&path, Some(&package))).unwrap();
        assert_ne!(generated.hash, next.hash);
        assert_eq!(
            fs::read(path.join("app.pkb")).unwrap(),
            b"changed original bytes"
        );
    }
    #[test]
    fn missing_relative_or_generic_package_inputs_fail() {
        let path = directory("invalid");
        fs::write(path.join("hero-main.js"), b"stale js").unwrap();
        let absent = path.join("absent.pkb");
        assert!(generate(config(&path, Some(&absent))).is_err());
        assert!(generate(config(&path, Some(Path::new("relative.pkb"))))
            .unwrap_err()
            .contains("absolute"));
        assert!(generate(config(&path, None))
            .unwrap_err()
            .contains("POCKETJS_EMBED_BUNDLE"));
        assert!(generate(Config {
            enabled: false,
            ..config(&path, Some(&absent))
        })
        .unwrap_err()
        .contains("generic runtime"));
        assert!(!path.join("bundle.rs").exists());
    }
    #[test]
    fn identities_and_the_generic_runtime_keep_their_values() {
        let path = directory("identity");
        let package = path.join("hero-main.pkb");
        fs::write(&package, b"bundle").unwrap();
        fs::write(path.join("hero-main.js"), b"a").unwrap();
        let sources = generate(Config {
            identity: Identity::Sources,
            ..config(&path, Some(&package))
        })
        .unwrap();
        assert_eq!(sources.hash, "af63dc4c8601ec8c");
        assert_eq!(
            sources.inputs,
            vec![
                package.clone(),
                path.join("hero-main.js"),
                path.join("hero-main.pak")
            ]
        );
        let generic = Config {
            enabled: false,
            ..config(&path, None)
        };
        assert_eq!(generate(generic).unwrap().hash, "none");
        assert_eq!(
            generate(Config {
                identity: Identity::Sources,
                enabled: false,
                ..config(&path, None)
            })
            .unwrap()
            .hash,
            fnv(&[])
        );
        assert_eq!(fs::read(path.join("app.pkb")).unwrap(), b"");
        assert!(fs::read_to_string(path.join("bundle.rs"))
            .unwrap()
            .contains("BUNDLE: &[u8] = &[]"));
    }
}
