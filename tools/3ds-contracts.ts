import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { OP } from "../contracts/spec/spec.ts";
import { hashPocketProfile, type PocketProfile } from "../framework/src/profile.ts";
import { POCKET_PROFILES } from "../hosts/index.ts";
import { profileFactsC } from "./profile-export.ts";
const profile = POCKET_PROFILES["3ds-dev"];

/** The product's profile facts, hash and operation numbers as one header. */
export function threeDsProfileHeader(selected: PocketProfile = profile): string {
  const hash = hashPocketProfile(selected).slice(7).match(/../g)!.map(byte => Number.parseInt(byte, 16));
  const operations = Object.entries(OP).map(([name, code]) => `#define POCKET_3DS_OP_${name} ${code}u`).join("\n");
  return `/* Generated by tools/3ds-contracts.ts from the registered 3DS profile. */\n#ifndef POCKET_3DS_PROFILE_H\n#define POCKET_3DS_PROFILE_H\n#include <stdint.h>\n#include "pocket_runtime.h"\n${profileFactsC(selected, "pocket_3ds_profile")}static const uint8_t pocket_3ds_profile_hash[32] = {${hash.join(",")}};\n${operations}\n#endif\n`;
}

export function ensureThreeDsProfileHeader(): void {
  const path = resolve(import.meta.dir, "../products/3ds/include/pocket_profile.h");
  const expected = threeDsProfileHeader();
  if (!existsSync(path) || readFileSync(path, "utf8") !== expected) writeFileSync(path, expected);
}
if (import.meta.main) {
  const path = resolve(import.meta.dir, "../products/3ds/include/pocket_profile.h");
  const expected = threeDsProfileHeader();
  if (process.argv.includes("--check")) {
    if (readFileSync(path, "utf8") !== expected) throw new Error("3DS profile header is stale");
  } else writeFileSync(path, expected);
}
