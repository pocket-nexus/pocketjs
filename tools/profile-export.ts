import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { canonicalProfileJson, profileHashProjection } from "../framework/src/profile.ts";
import { depfile } from "../framework/compiler/build-inputs.ts";
import type { ResolvedProfile } from "./profile-resolver.ts";
import { PROFILE_CAPABILITY_BITS, PROFILE_PRESENTATION_BITS } from "../contracts/spec/profile.ts";
import type { FixedDisplayProfile } from "../contracts/spec/platform-types.ts";
import { POCKET_BINDING_GENERATION } from "../contracts/spec/binding-generation.ts";

const cBytes = (text: string) => `"${[...new TextEncoder().encode(text)].map(byte => `\\x${byte.toString(16).padStart(2, "0")}`).join("")}"`;
function writeChanged(path: string, text: string): void {
  if (!existsSync(path) || readFileSync(path, "utf8") !== text) writeFileSync(path, text);
}
const cName = (name: string) => name.toUpperCase().replace(/[.-]/g, "_");
function capabilityMask(capabilities: readonly string[]): bigint {
  return capabilities.reduce((mask, capability) => {
    if (!Object.hasOwn(PROFILE_CAPABILITY_BITS, capability)) throw new Error(`profile export: unregistered capability ${capability}`);
    return mask | PROFILE_CAPABILITY_BITS[capability as keyof typeof PROFILE_CAPABILITY_BITS];
  }, 0n);
}
const uint64 = (value: bigint) => `UINT64_C(0x${value.toString(16)})`;
const viewport = (value: readonly [number, number]) => `{${value[0]}u, ${value[1]}u}`;
function logicalViewports(name: string, display: FixedDisplayProfile): string {
  return `static const pocket_profile_viewport ${name}[] = {${display.logicalViewports.map(viewport).join(", ")}};`;
}
function displayValue(name: string, display: FixedDisplayProfile): string {
  const presentations = display.presentations.reduce((bits, mode) => bits | PROFILE_PRESENTATION_BITS[mode], 0);
  return `{sizeof(pocket_profile_display), ${viewport(display.physicalViewport)}, ${name}, ${display.logicalViewports.length}u, ${presentations}u, ${display.rasterDensity}u}`;
}

/** Export the program's trusted identity before any application is loaded. */
export function exportProfile(resolved: ResolvedProfile, outdir: string, dependencyFile?: string) {
  const { profile, profileHash, hostAbi } = resolved;
  if (hostAbi !== POCKET_BINDING_GENERATION) throw new Error(`profile export: unsupported binding generation ${hostAbi}`);
  mkdirSync(outdir, { recursive: true });
  const canonical = canonicalProfileJson(profile);
  const hash = profileHash.slice(7).match(/../g)!.map(byte => Number.parseInt(byte, 16));
  const header = join(outdir, "pocket_profile.h");
  const sidecar = join(outdir, "pocket-profile.json");
  const { display } = profile;
  const auxiliary = display.auxiliary;
  const dynamic = display.dynamicViewport;
  writeChanged(header, `/* Generated by pocket profile export; do not edit. */
#ifndef POCKET_COMPILED_PROFILE_H
#define POCKET_COMPILED_PROFILE_H
#include <stddef.h>
#include <stdint.h>
/* Physical primary dimensions; logicalViewports may offer several sizes. */
#define POCKET_PROFILE_WIDTH ${display.physicalViewport[0]}u
#define POCKET_PROFILE_HEIGHT ${display.physicalViewport[1]}u
#define POCKET_PROFILE_TICK_HZ ${profile.tickHz}u
${Object.entries(PROFILE_CAPABILITY_BITS).map(([name, bit]) => `#define POCKET_PROFILE_CAP_${cName(name)} ${uint64(bit)}`).join("\n")}
${Object.entries(PROFILE_PRESENTATION_BITS).map(([name, bit]) => `#define POCKET_PROFILE_PRESENTATION_${cName(name)} ${bit}u`).join("\n")}
typedef struct pocket_profile_viewport {
    uint32_t width;
    uint32_t height;
} pocket_profile_viewport;
typedef struct pocket_profile_display {
    uint32_t struct_size;
    pocket_profile_viewport physical_viewport;
    const pocket_profile_viewport *logical_viewports;
    size_t logical_viewport_count;
    uint32_t presentations;
    uint32_t raster_density;
} pocket_profile_display;
typedef struct pocket_profile_dynamic_viewport {
    uint32_t struct_size;
    pocket_profile_viewport min;
    pocket_profile_viewport max;
    uint32_t accepts_fixed;
} pocket_profile_dynamic_viewport;
typedef struct pocket_compiled_profile {
    uint32_t struct_size;
    const uint8_t *profile_json;
    size_t profile_json_length;
    uint8_t profile_hash[32];
    uint32_t host_abi;
    uint32_t tick_hz;
    const char *id;
    const char *platform;
    const char *form;
    pocket_profile_display display;
    const pocket_profile_display *auxiliary_display;
    const pocket_profile_dynamic_viewport *dynamic_viewport;
    uint64_t capabilities;
    /* Additional grants for systemUI; application capabilities still apply. */
    uint64_t system_ui_capabilities;
} pocket_compiled_profile;
static const char pocket_profile_json_data[] = ${cBytes(canonical)};
static const char pocket_profile_id_data[] = ${cBytes(profile.id)};
static const char pocket_profile_platform_data[] = ${cBytes(profile.platform)};
static const char pocket_profile_form_data[] = ${cBytes(profile.form)};
${logicalViewports("pocket_profile_logical_viewports", display)}
${auxiliary ? `${logicalViewports("pocket_profile_auxiliary_viewports", auxiliary)}
static const pocket_profile_display pocket_profile_auxiliary_display = ${displayValue("pocket_profile_auxiliary_viewports", auxiliary)};` : ""}
${dynamic ? `static const pocket_profile_dynamic_viewport pocket_profile_dynamic = {sizeof(pocket_profile_dynamic_viewport), ${viewport(dynamic.min)}, ${viewport(dynamic.max)}, ${dynamic.acceptsFixed ? 1 : 0}u};` : ""}
static const pocket_compiled_profile pocket_profile = {
    sizeof(pocket_compiled_profile), (const uint8_t *)pocket_profile_json_data,
    sizeof(pocket_profile_json_data) - 1, {${hash.join(",")}},
    ${hostAbi}u, ${profile.tickHz}u, pocket_profile_id_data,
    pocket_profile_platform_data, pocket_profile_form_data,
    ${displayValue("pocket_profile_logical_viewports", display)},
    ${auxiliary ? "&pocket_profile_auxiliary_display" : "NULL"}, ${dynamic ? "&pocket_profile_dynamic" : "NULL"},
    ${uint64(capabilityMask(profile.capabilities))}, ${uint64(capabilityMask(profile.roleCapabilities?.systemUI ?? []))}
};
#endif
`);
  writeChanged(sidecar, JSON.stringify({
    format: "pocket-profile/1", profile: profileHashProjection(profile),
    canonicalProfileJson: canonical, profileHash, hostAbi,
  }, null, 2) + "\n");
  if (dependencyFile) {
    mkdirSync(dirname(dependencyFile), { recursive: true });
    writeFileSync(dependencyFile, depfile(header, resolved.dependencies) + depfile(sidecar, resolved.dependencies));
  }
  return { header, sidecar };
}
