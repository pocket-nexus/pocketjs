#!/usr/bin/env bun
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { UI_OPS } from "../contracts/spec/ui-ops.ts";
import { POCKET_BINDING_GENERATION } from "../contracts/spec/binding-generation.ts";

const root = resolve(import.meta.dir, "..");
export function generatedGuestWebBindings(): string {
  const descriptors = UI_OPS.filter(op => op.id !== null).map(({ id, name, args, result }) => ({ id, name, args, result }));
  return `// Generated by tools/guest-web-bindings.ts. Do not edit.\nexport const POCKET_BINDING_GENERATION = ${POCKET_BINDING_GENERATION};\nexport const UI_DESCRIPTORS = ${JSON.stringify(descriptors)};\n`;
}
if (import.meta.main) {
  const content = generatedGuestWebBindings();
  const path = resolve(root, "engine/guest-web/src/ui-descriptors.js");
  if (process.argv.includes("--check")) {
    if (readFileSync(path, "utf8") !== content) throw new Error("generated web guest descriptors differ");
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
  }
}
