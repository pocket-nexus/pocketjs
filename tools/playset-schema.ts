// bun tools/playset-schema.ts [--check]
//
// Writes engine/crates/pocket-playset/src/schema.rs from contracts/spec/playset.ts,
// so the kernels and the TS SDK read one layout. --check fails when the file
// on disk differs from what the spec produces.

import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import * as spec from "../contracts/spec/playset.ts";

const OUT = resolve(import.meta.dir, "../engine/crates/pocket-playset/src/schema.rs");

/** Layout tables index arrays; the rest are ids and bit sets. */
const LAYOUT = new Set([
  "PLAYSET_STRIDE", "PLAYSET_ENT", "PLAYSET_INTENT", "PLAYSET_EVENT_FIELD",
  "PLAYSET_CAMERA_FIELD", "PLAYSET_STAT", "PLAYSET_PART", "PLAYSET_ARCH",
  "PLAYSET_WEAPON", "PLAYSET_CAMERA", "PLAYSET_EMITTER", "PLAYSET_MODEL",
]);

function moduleName(name: string): string {
  return name.replace(/^PLAYSET_/, "").toLowerCase();
}

let rust = "// Generated by tools/playset-schema.ts from contracts/spec/playset.ts. Do not edit.\n#![allow(dead_code)]\n";
for (const [name, value] of Object.entries(spec)) {
  if (typeof value === "number") {
    rust += `\npub const ${name.replace(/^PLAYSET_/, "")}: usize = ${value};\n`;
    continue;
  }
  if (typeof value !== "object" || value === null) continue;
  const type = LAYOUT.has(name) ? "usize" : "u32";
  rust += `\npub mod ${moduleName(name)} {\n`;
  for (const [key, field] of Object.entries(value as Record<string, number>)) {
    rust += `    pub const ${key}: ${type} = ${field};\n`;
  }
  rust += "}\n";
}

if (process.argv.includes("--check")) {
  const current = readFileSync(OUT, "utf8");
  if (current !== rust) {
    console.error("schema.rs is stale: run bun tools/playset-schema.ts");
    process.exit(1);
  }
  console.log("schema.rs matches contracts/spec/playset.ts");
} else {
  writeFileSync(OUT, rust);
  console.log(`wrote ${OUT}`);
}
