#!/usr/bin/env bun
import { existsSync, readFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { DRIVER_ABI_CALLBACKS, DRIVER_ABI_CONSTANTS, DRIVER_ABI_RULES, DRIVER_ABI_STRUCTS, type AbiCallback, type AbiField, type AbiRecord } from "../contracts/spec/driver-abi.ts";
import { HOST_ABI_FUNCTIONS, RUNTIME_ABI_CALLBACKS, RUNTIME_ABI_CONSTANTS, RUNTIME_ABI_FUNCTIONS, RUNTIME_ABI_RULES, RUNTIME_ABI_STRUCTS } from "../contracts/spec/runtime-abi.ts";

const root = resolve(fileURLToPath(new URL("..", import.meta.url)));
const records = [...DRIVER_ABI_STRUCTS, ...RUNTIME_ABI_STRUCTS];
const callbacks = [...DRIVER_ABI_CALLBACKS, ...RUNTIME_ABI_CALLBACKS];
const banner = "Generated by tools/driver-contracts.ts from contracts/spec/{input,driver-abi,runtime-abi}.ts. Do not edit.";
const primitives: Record<string, string> = { void: "void", c_void: "void", c_char: "char", usize: "size_t", u8: "uint8_t", u16: "uint16_t", u32: "uint32_t", u64: "uint64_t", i32: "int32_t", i64: "int64_t", f32: "float", f64: "double", PocketRendererId: "pocket_renderer_id", PocketRuntime: "pocket_runtime" };
const array = (type: string) => type.match(/^\[(\w+); (\d+)\]$/);
function cType(type: string): string {
  if (primitives[type]) return primitives[type];
  if (type.startsWith("*const ")) {
    const child = cType(type.slice(7));
    return child.endsWith("*") ? `${child} const *` : `const ${child} *`;
  }
  if (type.startsWith("*mut ")) return `${cType(type.slice(5))} *`;
  const cb = callbacks.find(value => `Option<${value.name}>` === type);
  if (cb) return cb.cName;
  const record = records.find(value => value.name === type);
  if (record) return record.cName;
  throw new Error(`Unknown ABI type: ${type}`);
}
function cField(field: AbiField): string {
  const a = array(field.type);
  return a ? `${cType(a[1]!)} ${field.name}[${a[2]}]` : `${cType(field.type)} ${field.name}`;
}
function rustType(type: string): string { return type === "void" ? "()" : type; }

export interface AbiDataModel { pointerSize: number; pointerAlign: number; u64Align: number; i64Align: number; f64Align: number }
export interface AbiLayout { size: number; align: number; offsets?: number[] }
/** Target data models distinguish i686's four-byte u64 alignment from wasm/ARM. */
export function abiLayout(type: string, model: AbiDataModel): AbiLayout {
  if (type.startsWith("*") || type.startsWith("Option<") || type === "usize") return { size: model.pointerSize, align: model.pointerAlign };
  const scalars: Record<string, AbiLayout> = {
    u8: { size: 1, align: 1 }, u16: { size: 2, align: 2 }, u32: { size: 4, align: 4 }, i32: { size: 4, align: 4 }, f32: { size: 4, align: 4 },
    u64: { size: 8, align: model.u64Align }, i64: { size: 8, align: model.i64Align }, f64: { size: 8, align: model.f64Align },
  };
  if (scalars[type]) return scalars[type];
  const a = array(type);
  if (a) { const child = abiLayout(a[1]!, model); return { size: child.size * Number(a[2]), align: child.align }; }
  const record = records.find(value => value.name === type);
  if (!record) throw new Error(`Unknown layout type: ${type}`);
  let size = 0, align = 1;
  const offsets: number[] = [];
  for (const field of record.fields) {
    const child = abiLayout(field.type, model);
    size = Math.ceil(size / child.align) * child.align;
    offsets.push(size);
    size += child.size;
    align = Math.max(align, child.align);
  }
  return { size: Math.ceil(size / align) * align, align, offsets };
}

// Size is fixed by the scalar vocabulary; alignment comes from the target
// compiler. Pointer width alone cannot predict u64/i64/double alignment.
function layoutExpressions(type: string, lang: "c" | "rust"): { size: string; align: string } {
  const sizeOf = (type: string) => lang === "c" ? `sizeof(${cType(type)})` : `core::mem::size_of::<${type}>()`;
  const alignOf = (type: string) => lang === "c"
    ? ["u64", "i64", "f64"].includes(type) ? `offsetof(pocket_abi_${type}_alignment, value)` : `POCKET_ABI_ALIGNOF(${cType(type)})`
    : `core::mem::align_of::<${type}>()`;
  const a = array(type);
  if (a) {
    const child = layoutExpressions(a[1]!, lang);
    const size = a[2] === "1" ? child.size : child.size === "1" ? a[2]! : `${child.size} * ${a[2]}`;
    return { size, align: child.align };
  }
  if (type.startsWith("*") || type.startsWith("Option<") || type === "usize") return { size: sizeOf(type), align: alignOf(type) };
  const scalarSizes: Record<string, number> = { u8: 1, u16: 2, u32: 4, i32: 4, f32: 4, u64: 8, i64: 8, f64: 8 };
  if (scalarSizes[type]) return { size: String(scalarSizes[type]), align: alignOf(type) };
  throw new Error(`Inline records are not extensible ABI fields: ${type}; use a pointer`);
}
const cDoc = (doc?: string) => doc ? `/* ${doc} */\n` : "";
const rustDoc = (doc?: string) => doc ? `/// ${doc}\n` : "";
function cAssertions(record: AbiRecord): string {
  const prefix = `POCKET_LAYOUT_${record.cName.toUpperCase()}`;
  let previousEnd = "0", previousAlign = "1";
  const lines = ["enum {"];
  record.fields.forEach((field, index) => {
    const child = layoutExpressions(field.type, "c");
    lines.push(`  ${prefix}_${index}_OFFSET = POCKET_ABI_ALIGN_UP(${previousEnd}, ${child.align}),`);
    lines.push(`  ${prefix}_${index}_ALIGN = POCKET_ABI_MAX(${previousAlign}, ${child.align}),`);
    previousEnd = `${prefix}_${index}_OFFSET + ${child.size}`;
    previousAlign = `${prefix}_${index}_ALIGN`;
  });
  lines.push(`  ${prefix}_SIZE = POCKET_ABI_ALIGN_UP(${previousEnd}, ${previousAlign})`, "};");
  lines.push(`POCKET_ABI_ASSERT(sizeof(${record.cName}) == ${prefix}_SIZE, "${record.cName} size");`);
  lines.push(`POCKET_ABI_ASSERT(POCKET_ABI_ALIGNOF(${record.cName}) == ${previousAlign}, "${record.cName} alignment");`);
  record.fields.forEach((field, index) => lines.push(`POCKET_ABI_ASSERT(offsetof(${record.cName}, ${field.name}) == ${prefix}_${index}_OFFSET, "${record.cName}.${field.name}");`));
  return lines.join("\n") + "\n";
}
function cHeader(component: "drivers" | "runtime"): string {
  const ownRecords = component === "drivers" ? DRIVER_ABI_STRUCTS : RUNTIME_ABI_STRUCTS;
  const ownCallbacks = component === "drivers" ? DRIVER_ABI_CALLBACKS : RUNTIME_ABI_CALLBACKS;
  const constants = component === "drivers" ? DRIVER_ABI_CONSTANTS : RUNTIME_ABI_CONSTANTS;
  const rules = component === "drivers" ? DRIVER_ABI_RULES : RUNTIME_ABI_RULES;
  let result = `/* ${banner} */\n#pragma once\n#include <stddef.h>\n#include <stdint.h>\n`;
  result += component === "runtime" ? '#include "pocket_drivers.h"\n' : '#include "pocket_spec.h"\n';
  result += "\n" + rules.map(cDoc).join("") + "\n";
  result += '#ifdef __cplusplus\nextern "C" {\n#endif\n';
  if (component === "runtime") result += "typedef struct pocket_runtime pocket_runtime;\ntypedef uint32_t pocket_renderer_id;\n";
  result += Object.entries(constants).filter(([name]) => name !== "POCKET_ANALOG_CENTER" && name !== "POCKET_DRAW_LIST_VERSION").map(([name, value]) => `#define ${name} ${value < 0 ? `(${value})` : `${value}U`}\n`).join("");
  if (component === "drivers") {
    result += "/* Probe member alignment: i386 can align a scalar to 8 but its struct field to 4. */\n";
    for (const type of ["u64", "i64", "f64"]) result += `typedef struct { char prefix; ${cType(type)} value; } pocket_abi_${type}_alignment;\n`;
  }
  for (const record of ownRecords) result += `typedef struct ${record.cName} ${record.cName};\n`;
  for (const cb of ownCallbacks) result += `\n${cDoc(cb.doc)}typedef ${cType(cb.result)} (*${cb.cName})(${cb.args.map(cField).join(", ") || "void"});\n`;
  result += "\n#ifdef __cplusplus\n#define POCKET_ABI_ASSERT static_assert\n#define POCKET_ABI_ALIGNOF alignof\n#else\n#define POCKET_ABI_ASSERT _Static_assert\n#define POCKET_ABI_ALIGNOF _Alignof\n#endif\n";
  result += "#define POCKET_ABI_ALIGN_UP(size, align) (((size) + (align) - 1) / (align) * (align))\n#define POCKET_ABI_MAX(a, b) ((a) > (b) ? (a) : (b))\n";
  for (const record of ownRecords) {
    result += `\n${cDoc(record.doc)}struct ${record.cName} {\n`;
    for (const field of record.fields) result += `  ${cDoc(field.doc)}${cField(field)};\n`;
    result += "};\n" + cAssertions(record);
  }
  if (component === "runtime") for (const fn of [...RUNTIME_ABI_FUNCTIONS, ...HOST_ABI_FUNCTIONS]) result += `\n${cDoc(fn.doc)}${cType(fn.result)} ${fn.name}(${fn.args.map(cField).join(", ") || "void"});\n`;
  return result + "\n#undef POCKET_ABI_ASSERT\n#undef POCKET_ABI_ALIGNOF\n#undef POCKET_ABI_ALIGN_UP\n#undef POCKET_ABI_MAX\n#ifdef __cplusplus\n}\n#endif\n";
}
function rustCallback(cb: AbiCallback): string {
  return `${rustDoc(cb.doc)}pub type ${cb.name} = unsafe extern "C" fn(${cb.args.map(field => `${field.name}: ${rustType(field.type)}`).join(", ")}) -> ${rustType(cb.result)};\n`;
}
function rustTypes(): string {
  let result = `// ${banner}\nuse core::ffi::{c_char, c_void};\n\n`;
  result += [...DRIVER_ABI_RULES, ...RUNTIME_ABI_RULES].map(rule => `// ${rule}\n`).join("");
  result += "\npub type PocketRendererId = u32;\n#[repr(C)]\npub struct PocketRuntime { _private: [u8; 0] }\n";
  for (const [name, value] of Object.entries({ ...DRIVER_ABI_CONSTANTS, ...RUNTIME_ABI_CONSTANTS })) result += `pub const ${name}: ${name.startsWith("POCKET_STATUS_") ? "i32" : "u32"} = ${value};\n`;
  for (const cb of callbacks) result += "\n" + rustCallback(cb);
  for (const record of records) {
    result += `\n${rustDoc(record.doc)}#[repr(C)]\n#[derive(Clone, Copy, Debug)]\npub struct ${record.name} {\n`;
    for (const field of record.fields) result += `    ${rustDoc(field.doc)}pub ${field.name}: ${field.type},\n`;
    result += "}\n";
    result += `impl ${record.name} {
    /// An empty current-version record suitable for an output callback.
    pub fn empty() -> Self {
        let mut value: Self = unsafe { core::mem::zeroed() };
        value.struct_size = core::mem::size_of::<Self>();
        value
    }
    /// Copy only complete fields; absent fields remain zero/null.
    /// # Safety
    /// A nonnull pointer provides a readable usize prefix and valid field
    /// representations through min(struct_size, known size). No full-sized
    /// reference is formed from a possibly shorter caller allocation.
    pub unsafe fn read_prefix(pointer: *const Self) -> Option<Self> {
        if pointer.is_null() { return None; }
        let bytes = pointer.cast::<u8>();
        let capacity = unsafe { bytes.cast::<usize>().read_unaligned() };
        if capacity < core::mem::size_of::<usize>() || capacity > isize::MAX as usize { return None; }
        let mut value = Self::empty();
        value.struct_size = capacity;
`;
    for (const field of record.fields.slice(1)) result += `        if core::mem::offset_of!(Self, ${field.name}) + core::mem::size_of::<${field.type}>() <= capacity {
            value.${field.name} = unsafe { bytes.add(core::mem::offset_of!(Self, ${field.name})).cast::<${field.type}>().read_unaligned() };
        }
`;
    result += `        Some(value)
    }
    /// Preserve the caller's capacity and write only complete known fields.
    /// # Safety
    /// pointer provides a readable usize prefix and writable bytes through
    /// min(struct_size, known size), with no overlapping live references.
    pub unsafe fn write_prefix(self, pointer: *mut Self) -> bool {
        if pointer.is_null() { return false; }
        let bytes = pointer.cast::<u8>();
        let capacity = unsafe { bytes.cast::<usize>().read_unaligned() };
        if capacity < core::mem::size_of::<usize>() || capacity > isize::MAX as usize { return false; }
`;
    for (const field of record.fields.slice(1)) result += `        if core::mem::offset_of!(Self, ${field.name}) + core::mem::size_of::<${field.type}>() <= capacity {
            unsafe { bytes.add(core::mem::offset_of!(Self, ${field.name})).cast::<${field.type}>().write_unaligned(self.${field.name}); }
        }
`;
    result += `        true
    }
}
const _: () = {
    let mut size = 0usize;
    let mut align = 1usize;
`;

    for (const field of record.fields) {
      const child = layoutExpressions(field.type, "rust");
      result += `    let field_align = ${child.align};\n    size = size.div_ceil(field_align) * field_align;\n    assert!(core::mem::offset_of!(${record.name}, ${field.name}) == size);\n    size += ${child.size};\n    if field_align > align { align = field_align; }\n`;
    }
    result += `    assert!(core::mem::size_of::<${record.name}>() == size.div_ceil(align) * align);\n    assert!(core::mem::align_of::<${record.name}>() == align);\n};\n`;
  }
  result += '\nunsafe extern "C" {\n';
  for (const fn of [...RUNTIME_ABI_FUNCTIONS, ...HOST_ABI_FUNCTIONS]) result += `    ${rustDoc(fn.doc)}pub fn ${fn.name}(${fn.args.map(field => `${field.name}: ${rustType(field.type)}`).join(", ")}) -> ${rustType(fn.result)};\n`;
  return result + "}\n";
}

export function generatedDriverContracts(): Map<string, string> {
  return new Map([
    ["contracts/generated/pocket_drivers.h", cHeader("drivers")],
    ["contracts/generated/pocket_runtime.h", cHeader("runtime")],
    ["engine/drivers/src/abi.rs", rustTypes()],
  ]);
}

if (import.meta.main) {
  const check = Bun.argv.includes("--check");
  for (const [path, contents] of generatedDriverContracts()) {
    const file = resolve(root, path);
    if (check) {
      if (!existsSync(file) || readFileSync(file, "utf8") !== contents) throw new Error(`stale generated contract: ${path}`);
    } else await Bun.write(file, contents);
  }
}
